window.FC_I18N = (() => {
  function normalizeLang(raw) {
    if (!raw || raw === "auto") return null;
    const s = String(raw).toLowerCase().replace(/_/g, "-");
    if (s.startsWith("zh-tw") || s.startsWith("zh-hk") || s.startsWith("zh-hant")) return "zh-TW";
    if (s.startsWith("zh")) return "zh-CN";
    if (s.startsWith("ja")) return "ja";
    if (s.startsWith("ko")) return "ko";
    if (s.startsWith("es")) return "es";
    if (s.startsWith("fr")) return "fr";
    if (s.startsWith("de")) return "de";
    if (s.startsWith("en")) return "en";
    return null;
  }

  let saved = "auto";
  try { saved = localStorage.getItem("fc_lang") || "auto"; } catch (_) {}

  function detectHostLang() {
    try {
      const uxp = require("uxp");
      if (uxp && uxp.host && uxp.host.uiLocale) return normalizeLang(uxp.host.uiLocale);
    } catch (_) {}
    try {
      if (typeof navigator !== "undefined" && navigator.language) return normalizeLang(navigator.language);
    } catch (_) {}
    return "en";
  }

  function currentLang() {
    return normalizeLang(saved) || detectHostLang() || "en";
  }

  function setLang(code) {
    saved = code || "auto";
    try { localStorage.setItem("fc_lang", saved); } catch (_) {}
  }

  function getSavedLang() { return saved; }

  function t(key, ...args) {
    const tbl = window.FC_I18N_DATA[currentLang()] || window.FC_I18N_DATA.en;
    let s = (tbl && tbl[key]) || window.FC_I18N_DATA.en[key] || key;
    let idx = 0;
    s = s.replace(/%(%|\.(\d+)f|d|s)/g, (match, spec, prec) => {
      if (spec === "%") return "%";
      if (idx >= args.length) return match;
      const val = args[idx++];
      if (prec !== undefined) {
        const num = Number(val);
        return Number.isFinite(num) ? num.toFixed(Number(prec)) : String(val);
      }
      if (spec === "d") {
        const num = Number(val);
        return Number.isFinite(num) ? String(Math.round(num)) : String(val);
      }
      return String(val);
    });
    return s;
  }

  return { currentLang, setLang, getSavedLang, t };
})();
